export interface Book {
  id: string
  title: string
  author: string
  year: number
  categoryId: CategoryId
  /** Краткая аннотация для карточки и страницы книги. */
  annotation: string
  /** Ключевые слова/дисциплины для поиска. */
  tags: string[]
  /** Объём в страницах — показывается в карточке. */
  pages: number
  /** Подпись времени чтения из оригинала, например «6 ч чтения». */
  readTime?: string
  /** Показать в подборке избранного на главной. */
  featured?: boolean
  /** Эмодзи-обложка направления. */
  cover: string
  /** Текст книги в markdown для страницы чтения (/read/:id). */
  content: string
}

